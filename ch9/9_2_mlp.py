# 9.2 다층 퍼셉트론 (책 예제 ch09_06, ch09_07)
# 입력층(2개) → 은닉층(3개) → 출력층(2개)으로 값이 전달되는 과정을
# 행렬 곱으로 직접 계산해 본다. 가중치(W)와 편향(B)은 책에서 정해 준 값이다.
import numpy as np


def sigmoid(x):
    return 1 / (1 + np.exp(-x))


X = np.array([10, 20])                                  # 입력값 2개

# ---- 은닉층: 입력 2개 → 뉴런 3개
W1 = np.array([[0.1, 0.3, 0.5], [0.2, 0.4, 0.6]])       # 가중치 (2행 3열)
B1 = np.array([1, 2, 3])                                # 편향 3개
A1 = np.dot(X, W1) + B1                                 # 입력 × 가중치 + 편향
Z1 = sigmoid(A1)                                        # 활성화 함수 적용

print('[은닉층]')
print('A1 :', A1)
print('Z1 :', Z1)

# ---- 출력층: 뉴런 3개 → 출력 2개
W2 = np.array([[0.1, 0.4], [0.2, 0.5], [0.3, 0.6]])     # 가중치 (3행 2열)
B2 = np.array([0.1, 0.2])                               # 편향 2개
A2 = np.dot(Z1, W2) + B2
Y = sigmoid(A2)

print('[출력층]')
print('A2 :', A2)
print('Y  :', Y)
